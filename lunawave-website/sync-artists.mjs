// Copies data/artists.json (the app roster's source) into artists.js for the static site.
// Run from the repo root after editing the list: node lunawave-website/sync-artists.mjs
import { readFileSync, writeFileSync } from "node:fs";
const { artists } = JSON.parse(readFileSync("data/artists.json", "utf8"));
writeFileSync(
  "lunawave-website/artists.js",
  `// Generated by sync-artists.mjs from data/artists.json. Do not edit by hand.\nwindow.LW_ARTISTS = ${JSON.stringify(artists.map((a) => [a.name, a.genre, a.tier]))};\n`,
);
console.log(`${artists.length} artists written`);
